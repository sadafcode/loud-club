/** Deterministic 0..1 value from a string, so stock is identical on server and client. */
function seeded(key: string) {
  let h = 2166136261;
  for (let i = 0; i < key.length; i++) {
    h ^= key.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return ((h >>> 0) % 1000) / 1000;
}

function buildVariants(id: string, colors: Color[], sizes: string[]): Variant[] {
  return colors.flatMap((color) =>
    sizes.map((size) => {
      const sku = `${id}-${color.name.toLowerCase().replace(/\s+/g, "-")}-${size.toLowerCase()}`;
      const r = seeded(sku);
      // ~12% sold out, ~25% low stock (1–4), the rest comfortably stocked.
      const stock = r < 0.12 ? 0 : r < 0.37 ? 1 + Math.floor(r * 10) % 4 : 6 + Math.floor(r * 40);
      return { sku, color: color.name, size, stock };
    }),
  );
}

type ProductInput = Omit<Product, "variants" | "sizes" | "slug"> & { sizes?: string[] };

function product(input: ProductInput): Product {
  const sizes = input.sizes ?? SIZE_RUNS[input.sizeSystem];
  return {
    ...input,
    slug: input.id,
    sizes,
    variants: buildVariants(input.id, input.colors, sizes),
  };
}

